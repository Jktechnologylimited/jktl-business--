import "server-only";
import { getSql } from "@/lib/db/client";
import { getIndustry } from "@/lib/industry";
import { getPack } from "@/lib/ai/industry-packs";
import { buildSiteSeed } from "@/lib/prospects/site-builder";
import { enrichmentCompleteness, enrichmentFromRaw, enrichmentGaps } from "@/lib/prospects/enrichment";
import { mirrorGallery } from "@/lib/prospects/image-mirror";
import { recordSiteBuilt } from "@/lib/db/prospects";
import type { BusinessType } from "@/lib/types";
import type { Prospect, ProspectInput } from "@/lib/prospects/types";

/**
 * Builds one prospect's website.
 *
 * Extracted from the admin action so the single-build path and the bulk job use
 * the same code. They must not diverge: a site generated by the batch has to be
 * identical to one generated by hand, or the admin ends up with two subtly
 * different products and no way to tell which a given business received.
 *
 * The whole thing is idempotent-ish and resumable by design — every write is a
 * fresh insert against a newly generated organization id, and the caller records
 * a per-target outcome, so a crash mid-batch loses at most the site in flight.
 */

export interface SiteBuildResult {
  ok: true;
  organizationId: string;
  subdomain: string;
  url: string;
  contentScore: number;
  contentGaps: string[];
  imagesMirrored: number;
  imageBytes: number;
  servicesCreated: number;
}

export type SiteBuildOutcome =
  | SiteBuildResult
  | { ok: false; reason: string };

function appOrigin(): string {
  const explicit = process.env.NEXT_PUBLIC_APP_URL;
  if (explicit) return explicit.replace(/\/+$/, "");
  return `https://${process.env.NEXT_PUBLIC_ROOT_DOMAIN || "jktl.com.ng"}`;
}

/**
 * Generates a subdomain that is actually free.
 *
 * Subdomains are globally unique, so two "Bright Smile" clinics in two cities
 * must not collide. The loop is bounded and the final check is deliberate: a
 * silent overwrite would replace a live customer's site with a prospect's.
 */
async function availableSubdomain(base: string): Promise<string | null> {
  const sql = getSql();
  for (let attempt = 1; attempt <= 20; attempt += 1) {
    const candidate = attempt === 1 ? base : `${base}-${attempt}`.slice(0, 60);
    const taken = await sql`SELECT 1 FROM business_profiles WHERE subdomain = ${candidate} LIMIT 1`;
    if (!taken[0]) return candidate;
  }
  return null;
}

export async function buildOneSite(prospect: Prospect, jobId?: string): Promise<SiteBuildOutcome> {
  const sql = getSql();
  const niche = (prospect.niche || "general") as BusinessType;

  // Parse the scraped listing into real content: their photographs, their
  // reviews, their opening hours. This is the difference between a themed
  // template and their actual business.
  const enrichment = enrichmentFromRaw(prospect.enrichment ?? {}, prospect.city);

  // Photographs are moved onto our own storage before anything is written, so the
  // site never carries a URL that can disappear from under it.
  const gallery = enrichment.photos.length > 0 ? await mirrorGallery(enrichment.photos.map((p) => p.url)) : null;
  if (gallery) {
    enrichment.photos = enrichment.photos.map((photo, index) => ({ ...photo, url: gallery.urls[index] ?? photo.url }));
  }

  const seed = buildSiteSeed(
    {
      source: prospect.source,
      sourceRef: prospect.sourceRef,
      businessName: prospect.businessName,
      niche: (prospect.niche || "general") as ProspectInput["niche"],
      category: prospect.category,
      phone: prospect.phone,
      email: prospect.email,
      address: prospect.address,
      city: prospect.city,
      state: prospect.state,
      country: prospect.country,
      website: prospect.website,
      rating: prospect.rating,
      reviews: prospect.reviews,
      latitude: prospect.latitude,
      longitude: prospect.longitude,
    },
    {
      industry: getIndustry(niche),
      pack: getPack(niche),
      enrichment,
      contentScore: enrichmentCompleteness(enrichment),
      contentGaps: enrichmentGaps(enrichment),
    },
  );

  const subdomain = await availableSubdomain(seed.subdomain);
  if (!subdomain) return { ok: false, reason: "Could not find a free subdomain" };

  const orgId = crypto.randomUUID();
  await sql`
    INSERT INTO organizations (id, name, slug, is_prospect)
    VALUES (${orgId}, ${prospect.businessName}, ${subdomain}, true)
  `;

  await sql`
    INSERT INTO business_profiles (
      organization_id, business_type, display_name, phone, email, address, city, state,
      subdomain, published, tagline, theme_color, about_text, about_long, font_pair_id,
      gallery_urls, opening_hours, service_areas, faqs, generated_from_prospect, generated_by_job, prospect_id
    )
    VALUES (
      ${orgId}, ${prospect.niche || "general"}, ${prospect.businessName}, ${prospect.phone}, ${prospect.email},
      ${prospect.address}, ${prospect.city}, ${prospect.state}, ${subdomain}, true,
      ${seed.tagline}, ${seed.themeColor}, ${seed.aboutText}, ${seed.aboutLong}, ${seed.fontPairId},
      ${seed.gallery.map((g) => g.url)}, ${JSON.stringify(seed.openingHours)}::jsonb,
      ${seed.serviceAreas}, ${JSON.stringify(seed.faqs)}::jsonb, ${prospect.id}, ${jobId ?? null}, ${prospect.id}
    )
  `;

  // Real reviews become testimonials, quoted verbatim and attributed. Nothing is
  // invented: a fabricated testimonial published in a business's own name is a
  // liability they never asked for.
  if (seed.testimonials.length > 0) {
    for (const testimonial of seed.testimonials) {
      await sql`
        INSERT INTO testimonials (organization_id, customer_name, rating, text, published)
        VALUES (${orgId}, ${testimonial.author}, ${testimonial.rating}, ${testimonial.text}, true)
      `;
    }
  }

  if (seed.products.length > 0) {
    for (const product of seed.products) {
      await sql`
        INSERT INTO products (organization_id, name, description, price_kobo, active)
        VALUES (${orgId}, ${product.name}, ${product.description}, 0, true)
      `;
    }
  }

  for (const service of seed.services) {
    await sql`
      INSERT INTO services (organization_id, name, category, price_kobo, duration_min, description, active)
      VALUES (${orgId}, ${service.name}, ${service.category}, ${service.priceKobo}, ${service.durationMin}, ${service.description}, true)
    `;
  }

  await recordSiteBuilt(prospect.id, orgId, subdomain);

  return {
    ok: true,
    organizationId: orgId,
    subdomain,
    url: `${appOrigin()}/sites/${subdomain}`,
    contentScore: seed.contentScore,
    contentGaps: seed.contentGaps,
    imagesMirrored: gallery?.mirrored ?? 0,
    imageBytes: gallery?.bytes ?? 0,
    servicesCreated: seed.services.length,
  };
}
