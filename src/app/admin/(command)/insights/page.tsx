import { PageHeader } from "@/components/app/page-header";
import { StatTile } from "@/components/app/stat-tile";
import { loadInsightInput } from "@/lib/db/admin-insights";
import { buildInsights } from "@/lib/admin-insights";
import { formatKobo } from "@/lib/format";
import { IntegrationHealth } from "@/components/admin/integration-health";
import { RunDailySweep } from "@/components/admin/run-daily-sweep";

export const dynamic = "force-dynamic";

/**
 * The operator's view of the whole business.
 *
 * Five headline numbers chosen for what somebody would act on tomorrow — money
 * collected, calls rescued, businesses, partner cost, leads qualified — then the
 * detail behind each. Deliberately not a wall of charts: a dashboard that shows
 * everything teaches an operator to read nothing.
 *
 * Two numbers are intentionally absent, because they cannot be computed honestly
 * yet: the receptionist's *answer* rate (we only see missed calls) and the lead
 * engine's cost per acquisition (nothing has converted).
 */
export default async function AdminInsightsPage() {
  const input = await loadInsightInput();
  const insights = buildInsights(input, (kobo) => formatKobo(kobo));
  const { growth, revenue, receptionist, affiliates, prospects, markets } = insights;

  return (
    <div className="flex flex-col gap-6">
      <PageHeader title="Business insights" />
      <p className="-mt-2 text-sm text-ink-muted">
        Everything across every business — counts and money only. No customer names, bookings or chat transcripts leave
        a tenant&apos;s account.
      </p>

      {/* The five numbers. */}
      <div className="grid grid-cols-1 gap-3 sm:grid-cols-2 lg:grid-cols-5">
        {insights.headlines.map((headline) => (
          <div key={headline.label} className="rounded-2xl border border-border bg-paper p-4">
            <p className="text-xs font-medium text-ink-muted">{headline.label}</p>
            <p className="mt-1 font-display text-xl font-semibold text-ink">{headline.value}</p>
            <p className="mt-1 text-[11px] leading-snug text-ink-faint">{headline.sub}</p>
          </div>
        ))}
      </div>

      {/* Growth */}
      <section className="rounded-2xl border border-border bg-paper p-4">
        <h2 className="font-display text-sm font-semibold text-ink">Businesses</h2>
        <p className="mt-1 text-xs text-ink-muted">
          {growth.totalBusinesses.toLocaleString()} real {growth.totalBusinesses === 1 ? "business" : "businesses"} ·{" "}
          {growth.published.toLocaleString()} published · {growth.prospects.toLocaleString()} prospect sites generated by
          the lead engine, which are tenants but not customers.
        </p>

        <div className="mt-4 flex items-end gap-2" aria-hidden>
          {growth.series.map((point) => {
            const tallest = Math.max(1, ...growth.series.map((p) => p.signups));
            const height = Math.round((point.signups / tallest) * 64);
            return (
              <div key={point.month} className="flex flex-1 flex-col items-center gap-1">
                <div className="flex h-16 w-full items-end">
                  <div
                    className="w-full rounded-t bg-primary/70"
                    style={{ height: `${Math.max(point.signups > 0 ? 6 : 2, height)}px` }}
                  />
                </div>
                <span className="text-[10px] text-ink-faint">{point.month.slice(5)}</span>
                <span className="text-[10px] font-medium text-ink-muted">{point.signups}</span>
              </div>
            );
          })}
        </div>
        <p className="mt-2 text-xs text-ink-faint">
          New businesses per month. Signups this month: {growth.signupsThisMonth}
          {growth.monthOnMonthPct === null
            ? "."
            : ` — ${growth.monthOnMonthPct > 0 ? "up" : "down"} ${Math.abs(growth.monthOnMonthPct)}% on last month.`}
        </p>
      </section>

      {/* Revenue */}
      <section className="rounded-2xl border border-border bg-paper p-4">
        <h2 className="font-display text-sm font-semibold text-ink">Revenue</h2>
        <div className="mt-3 grid grid-cols-2 gap-3 lg:grid-cols-4">
          <StatTile label="Collected" value={formatKobo(revenue.collectedKobo)} rule="primary" />
          <StatTile label="Still to come" value={formatKobo(revenue.outstandingKobo)} sub="Remaining setup months" rule="info" />
          <StatTile label="Monthly recurring" value={formatKobo(revenue.mrrKobo)} sub={`${formatKobo(revenue.arrKobo)}/yr`} rule="accent" />
          <StatTile label="Average collected" value={formatKobo(revenue.averageCollectedKobo)} sub="Per paying contract" />
        </div>
        <p className="mt-3 text-xs text-ink-muted">
          {revenue.active} active · {revenue.pastDue} past due · {revenue.pending} not started · {revenue.cancelled}{" "}
          cancelled.
          {revenue.payingRatePct === null
            ? " No contract has started yet."
            : ` ${revenue.payingRatePct}% of started contracts have paid.`}
        </p>
        {revenue.pastDue > 0 ? (
          <p className="mt-2 rounded-xl bg-danger-soft px-3 py-2 text-xs text-danger">
            {revenue.pastDue} contract{revenue.pastDue === 1 ? "" : "s"} past due — the daily job retries, but a dead card
            needs a person.
          </p>
        ) : null}
      </section>

      {/* The receptionist */}
      <section className="rounded-2xl border border-border bg-paper p-4">
        <h2 className="font-display text-sm font-semibold text-ink">The receptionist</h2>
        <p className="mt-1 text-xs text-ink-muted">
          Three rates, because they fail for different reasons: no text is a wallet or a Twilio problem, no chat opened is
          the message copy, no booking is the assistant or the clinic&apos;s service list.
        </p>
        <div className="mt-3 grid grid-cols-2 gap-3 lg:grid-cols-4">
          <StatTile label="Calls intercepted" value={receptionist.total.toLocaleString()} />
          <StatTile
            label="Got a text"
            value={receptionist.textCoveragePct === null ? "—" : `${receptionist.textCoveragePct}%`}
            sub={`${receptionist.textsSent} sent`}
            rule="info"
          />
          <StatTile
            label="Opened the chat"
            value={receptionist.openRatePct === null ? "—" : `${receptionist.openRatePct}%`}
            sub={`${receptionist.chatsOpened} opened`}
            rule="accent"
          />
          <StatTile
            label="Became a booking"
            value={receptionist.chatToBookingPct === null ? "—" : `${receptionist.chatToBookingPct}%`}
            sub={`${receptionist.bookings} booked`}
            rule="primary"
          />
        </div>
        <p className="mt-3 text-xs text-ink-muted">
          {formatKobo(receptionist.recoveredKobo)} attributed to intercepted calls, at{" "}
          {formatKobo(receptionist.averageRecoveredKobo)} a booking. At this rate that is{" "}
          {formatKobo(receptionist.annualisedRecoveredKobo)} a year across all businesses.
        </p>
        <p className="mt-2 text-xs text-ink-faint">
          {formatKobo(insights.wallet.totalBalanceKobo)} sitting in communication wallets
          {insights.wallet.emptyWallets > 0
            ? ` · ${insights.wallet.emptyWallets} business${insights.wallet.emptyWallets === 1 ? "" : "es"} cannot cover next month's line`
            : ""}
          .
        </p>
      </section>

      {/* Affiliates */}
      <section className="rounded-2xl border border-border bg-paper p-4">
        <h2 className="font-display text-sm font-semibold text-ink">Partners</h2>
        <div className="mt-3 grid grid-cols-2 gap-3 lg:grid-cols-4">
          <StatTile label="Applications" value={affiliates.applications.toLocaleString()} sub={`${affiliates.approved} approved`} />
          <StatTile label="Referrals" value={affiliates.referrals.toLocaleString()} sub={`${affiliates.convertedReferrals} converted`} rule="info" />
          <StatTile label="Commission earned" value={formatKobo(affiliates.earnedKobo)} sub={`${formatKobo(affiliates.pendingKobo)} held`} rule="accent" />
          <StatTile label="Owed to partners" value={formatKobo(affiliates.owedKobo)} sub={`${formatKobo(affiliates.paidOutKobo)} paid out`} rule="primary" />
        </div>
        <p className="mt-3 text-xs text-ink-muted">
          {affiliates.approvalRatePct === null ? "No applications yet" : `${affiliates.approvalRatePct}% approved`}
          {affiliates.referralConversionPct === null
            ? " · no referrals yet"
            : ` · ${affiliates.referralConversionPct}% of referrals converted`}
          {affiliates.convertedReferrals > 0
            ? ` · ${formatKobo(affiliates.averagePerReferralKobo)} per converted referral · ${formatKobo(affiliates.monthlyRunRateKobo)}/month recurring`
            : ""}
          .
        </p>
      </section>

      {/* Lead engine */}
      <section className="rounded-2xl border border-border bg-paper p-4">
        <h2 className="font-display text-sm font-semibold text-ink">Lead engine</h2>
        <div className="mt-3 grid grid-cols-2 gap-3 lg:grid-cols-4">
          <StatTile label="Leads" value={prospects.total.toLocaleString()} sub={`${prospects.excluded} already customers`} />
          <StatTile
            label="Qualified"
            value={prospects.qualified.toLocaleString()}
            sub={prospects.qualificationRatePct === null ? "Nothing audited yet" : `${prospects.qualificationRatePct}% of leads`}
            rule="info"
          />
          <StatTile
            label="Sites built"
            value={prospects.sitesBuilt.toLocaleString()}
            sub={prospects.siteCoveragePct === null ? "—" : `${prospects.siteCoveragePct}% of qualified`}
            rule="accent"
          />
          <StatTile
            label="Emails sent"
            value={prospects.emailsSent.toLocaleString()}
            sub={`${prospects.sendableEmails} sendable addresses`}
            rule="primary"
          />
        </div>
        <p className="mt-3 text-xs text-ink-muted">
          {prospects.blocked > 0 ? `${prospects.blocked} held by a country rule · ` : ""}
          {prospects.emailsPerConversion === null
            ? "No conversion yet, so cost per acquisition is not a number yet."
            : `${prospects.emailsPerConversion} emails per converted referral.`}
        </p>
      </section>

      {/* Markets */}
      {markets.length > 0 ? (
        <section className="rounded-2xl border border-border bg-paper p-4">
          <h2 className="font-display text-sm font-semibold text-ink">By market</h2>
          <ul className="mt-3 flex flex-col gap-2">
            {markets.map((market) => (
              <li key={market.countryCode} className="flex items-center gap-3">
                <span className="w-10 text-xs font-semibold text-ink">{market.countryCode}</span>
                <div className="h-2 flex-1 overflow-hidden rounded-full bg-surface">
                  <div className="h-full rounded-full bg-primary" style={{ width: `${market.sharePct}%` }} />
                </div>
                <span className="w-16 text-right text-xs text-ink-muted">{market.businesses}</span>
              </li>
            ))}
          </ul>
          <p className="mt-2 text-xs text-ink-faint">
            Côte d&apos;Ivoire and Senegal cannot take a payment yet — no Paystack, and the product is English only.
          </p>
        </section>
      ) : null}

      <RunDailySweep />

      <IntegrationHealth />
    </div>
  );
}
